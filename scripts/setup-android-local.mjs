/**
 * local.properties + Gradle JDK + 에뮬레이터/실기기 URL
 * node scripts/setup-android-local.mjs
 * node scripts/setup-android-local.mjs --device physical  (adb reverse용 127.0.0.1)
 */
import fs from "fs";
import path from "path";
import os from "os";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const androidDir = path.join(root, "apps/android");
const physical = process.argv.includes("--device") && process.argv.includes("physical");

const sdkCandidates = [
  process.env.ANDROID_HOME,
  process.env.ANDROID_SDK_ROOT,
  path.join(process.env.LOCALAPPDATA || "", "Android", "Sdk"),
  path.join(os.homedir(), "AppData", "Local", "Android", "Sdk")
].filter(Boolean);

const sdkDir = sdkCandidates.find((p) => fs.existsSync(p)) || sdkCandidates[0] || "";

const apiUrl = physical
  ? "http://127.0.0.1:8788"
  : "http://10.0.2.2:8788";
const webUrl = physical
  ? "http://127.0.0.1:5173"
  : "http://10.0.2.2:5173";

const lines = [
  "# Auto-generated by scripts/setup-android-local.mjs",
  sdkDir ? `sdk.dir=${sdkDir.replace(/\\/g, "\\\\")}` : "# sdk.dir=C\\\\:\\\\Users\\\\YOU\\\\AppData\\\\Local\\\\Android\\\\Sdk",
  `vlue.api.base.url=${apiUrl}`,
  `vlue.web.base.url=${webUrl}`,
  ""
];

const localPropsPath = path.join(androidDir, "local.properties");
fs.mkdirSync(androidDir, { recursive: true });
fs.writeFileSync(localPropsPath, lines.join("\n"), "utf8");
console.log("Wrote", localPropsPath);
console.log("  API:", apiUrl);
console.log("  WEB:", webUrl);
if (physical) {
  console.log("\n실기기 테스트 전 터미널에서:");
  console.log("  adb reverse tcp:8788 tcp:8788");
  console.log("  adb reverse tcp:5173 tcp:5173");
} else {
  console.log("\n에뮬레이터: PC에서 npm run dev 와 npm run api:dev 가 떠 있어야 합니다.");
}

const jbrCandidates = [
  process.env.ANDROID_STUDIO_JBR,
  process.env.JAVA_HOME,
  "C:\\Program Files\\Android\\Android Studio\\jbr",
  "C:\\Program Files\\Android\\Android Studio1\\jbr",
  "D:\\Program Files\\Android\\Android Studio\\jbr",
  path.join(process.env.LOCALAPPDATA || "", "Programs", "Android", "Android Studio", "jbr"),
  "C:\\Program Files\\Microsoft\\jdk-17.0.13.11-hotspot",
  "C:\\Program Files\\Eclipse Adoptium\\jdk-17.0.13.13-hotspot"
].filter(Boolean);

const jbr = jbrCandidates.find((p) => fs.existsSync(path.join(p, "bin", "java.exe")));
const gradlePropsPath = path.join(androidDir, "gradle.properties");
let gradleProps = fs.existsSync(gradlePropsPath) ? fs.readFileSync(gradlePropsPath, "utf8") : "";
if (jbr) {
  const esc = jbr.replace(/\\/g, "/");
  const line = `org.gradle.java.home=${esc}`;
  if (/org\.gradle\.java\.home=/.test(gradleProps)) {
    gradleProps = gradleProps.replace(/org\.gradle\.java\.home=.*/g, line);
  } else {
    gradleProps += `\n${line}\n`;
  }
  fs.writeFileSync(gradlePropsPath, gradleProps, "utf8");
  console.log("Gradle JDK:", jbr);
} else {
  console.warn("Android Studio JBR not found — JDK 17+ required for Gradle 8");
}
